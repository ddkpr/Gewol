let lang = "id";
try {
  const saved = localStorage.getItem("lang");
  if (saved === "id" || saved === "en") lang = saved;
  else if ((navigator.language || "").toLowerCase().startsWith("id")) lang = "id";
  else lang = "en"; // pengunjung luar negeri otomatis melihat bahasa Inggris
} catch (e) {}
const t = (key) => I18N[lang][key] ?? I18N.id[key] ?? key;

function applyLang(next) {
  lang = next;
  try { localStorage.setItem("lang", lang); } catch (e) {}
  document.documentElement.lang = lang;
  document.title = t("title");
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", t("meta"));
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    el.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attr, key] = pair.split(":");
      el.setAttribute(attr.trim(), t(key.trim()));
    });
  });
  document.querySelectorAll("#langToggle [data-l]").forEach((s) => s.classList.toggle("on", s.dataset.l === lang));
  words = I18N[lang].words;
  wordIndex = 0; charIndex = 0; deleting = false;
  if (window.renderLive) window.renderLive();
}

