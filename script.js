// ===== Suara klik (dibuat dengan WebAudio, tanpa file audio) =====
(function sound() {
  const btn = document.getElementById("soundToggle");
  let on = true;
  try { on = localStorage.getItem("sound") !== "off"; } catch (e) {}
  btn.textContent = on ? "🔊" : "🔇";

  let ctx;
  function blip() {
    if (!on) return;
    try {
      ctx = ctx || new (window.AudioContext || window.webkitAudioContext)();
      const t = ctx.currentTime;
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = "triangle";
      osc.frequency.setValueAtTime(880, t);
      osc.frequency.exponentialRampToValueAtTime(1320, t + 0.08);
      gain.gain.setValueAtTime(0.0001, t);
      gain.gain.exponentialRampToValueAtTime(0.12, t + 0.01);
      gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.14);
      osc.connect(gain).connect(ctx.destination);
      osc.start(t);
      osc.stop(t + 0.15);
    } catch (e) {}
  }

  document.addEventListener("click", (e) => {
    if (e.target.closest("a, button, [data-copy]")) blip();
  });
  btn.addEventListener("click", () => {
    on = !on;
    btn.textContent = on ? "🔊" : "🔇";
    try { localStorage.setItem("sound", on ? "on" : "off"); } catch (e) {}
  });
})();

// ===== Penghitung angka naik otomatis =====
(function counters() {
  const els = document.querySelectorAll(".count");
  const fmt = new Intl.NumberFormat("id-ID");

  function run(el) {
    const target = parseInt(el.dataset.count, 10) || 0;
    const from = el._val || 0;          // mulai dari angka yang sedang tampil
    const suffix = el.dataset.suffix || "";
    const dur = 1800;
    const start = performance.now();
    el._val = target;
    el.dataset.ran = "1";
    function step(now) {
      const t = Math.min((now - start) / dur, 1);
      const eased = 1 - Math.pow(1 - t, 3);
      el.textContent = fmt.format(Math.round(from + (target - from) * eased)) + (t === 1 ? suffix : "");
      if (t < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
  }
  window.runCounter = run; // dipakai oleh sinkronisasi

  const io = new IntersectionObserver((entries) => {
    entries.forEach((en) => {
      if (en.isIntersecting) {
        run(en.target);
        io.unobserve(en.target);
      }
    });
  }, { threshold: 0.5 });
  els.forEach((el) => io.observe(el));
})();

