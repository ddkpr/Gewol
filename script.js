function onCooldown(key, seconds) {
  try { return Date.now() - Number(localStorage.getItem(key) || 0) < seconds * 1000; } catch (e) { return false; }
}
function markCooldown(key) {
  try { localStorage.setItem(key, String(Date.now())); } catch (e) {}
}

function bindForm(form, opts) {
  if (!form) return;
  const statusEl = form.querySelector(".form-status");
  const btn = form.querySelector('button[type="submit"]');
  const setStatus = (cls, key) => { statusEl.className = "form-status " + cls; statusEl.textContent = t(key); };

  form.addEventListener("submit", async (e) => {
    e.preventDefault();
    // Kolom jebakan untuk bot: manusia tidak melihatnya, jadi jika terisi, abaikan diam-diam
    if (form.elements._gotcha && form.elements._gotcha.value) { setStatus("ok", opts.okKey); return; }
    if (opts.cooldownKey && onCooldown(opts.cooldownKey, opts.cooldownSec)) { setStatus("err", "req_wait"); return; }
    if (form.action.includes("ID_FORMSPREE_KAMU")) { setStatus("err", "form_unlinked"); return; }

    btn.disabled = true;
    btn.textContent = t("sending");
    statusEl.textContent = "";
    try {
      const res = await fetch(form.action, {
        method: "POST",
        body: new FormData(form),
        headers: { Accept: "application/json" },
      });
      if (!res.ok) throw new Error("gagal");
      setStatus("ok", opts.okKey);
      form.reset();
      if (opts.cooldownKey) markCooldown(opts.cooldownKey);
    } catch (err) {
      setStatus("err", "form_fail");
    } finally {
      btn.disabled = false;
      btn.textContent = t(btn.dataset.i18n);
    }
  });
}
