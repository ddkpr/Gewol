(function lightbox() {
  const box = document.getElementById("lightbox");
  const img = box.querySelector(".lb-figure img");
  const titleEl = document.getElementById("lbTitle");
  const descEl = document.getElementById("lbDesc");
  const countEl = document.getElementById("lbCount");
  const closeBtn = box.querySelector(".lb-close");
  const prevBtn = box.querySelector(".lb-nav.prev");
  const nextBtn = box.querySelector(".lb-nav.next");
  const cards = Array.from(document.querySelectorAll(".photo-card")).filter((c) => c.querySelector("img[data-full]"));
  if (!cards.length) return;
  const multi = cards.length > 1;
  prevBtn.hidden = nextBtn.hidden = !multi;
  countEl.hidden = !multi;

  let index = 0;
  let lastFocus = null;

  function render() {
    const card = cards[index];
    const src = card.querySelector("img[data-full]");
    img.classList.remove("in");
    img.onload = () => img.classList.add("in");
    img.src = src.getAttribute("data-full");
    img.alt = src.alt;
    if (img.complete && img.naturalWidth) img.classList.add("in");
    titleEl.textContent = (card.querySelector("h3") || {}).textContent || "";
    descEl.textContent = (card.querySelector("p") || {}).textContent || "";
    countEl.textContent = (index + 1) + " / " + cards.length;
    if (multi) { // muat foto tetangga lebih dulu agar perpindahan terasa instan
      [1, -1].forEach((d) => {
        const n = cards[(index + d + cards.length) % cards.length].querySelector("img[data-full]");
        new Image().src = n.getAttribute("data-full");
      });
    }
  }
  function open(i) {
    lastFocus = document.activeElement;
    index = i;
    render();
    box.classList.add("open");
    box.setAttribute("aria-hidden", "false");
    document.body.classList.add("lb-open");
    closeBtn.focus({ preventScroll: true });
  }
  function close() {
    box.classList.remove("open");
    box.setAttribute("aria-hidden", "true");
    document.body.classList.remove("lb-open");
    if (lastFocus && lastFocus.focus) lastFocus.focus({ preventScroll: true });
  }
  function step(d) {
    index = (index + d + cards.length) % cards.length;
    render();
  }

  cards.forEach((card, i) => {
    const im = card.querySelector("img[data-full]");
    im.tabIndex = 0;
    im.setAttribute("role", "button");
    im.addEventListener("click", () => open(i));
    im.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); open(i); }
    });
  });

  closeBtn.addEventListener("click", close);
  prevBtn.addEventListener("click", () => step(-1));
  nextBtn.addEventListener("click", () => step(1));

  // Geser jari / seret mouse
  let startX = null, startY = null, swiped = false;
  box.addEventListener("pointerdown", (e) => {
    swiped = false;
    if (e.target.closest("button")) return;
    startX = e.clientX; startY = e.clientY;
  });
  box.addEventListener("pointerup", (e) => {
    if (startX === null) return;
    const dx = e.clientX - startX, dy = e.clientY - startY;
    startX = null;
    if (multi && Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.5) {
      swiped = true;
      step(dx < 0 ? 1 : -1);
    }
  });
  box.addEventListener("pointercancel", () => { startX = null; });
  box.addEventListener("click", (e) => { if (e.target === box && !swiped) close(); });

  // Keyboard: Esc, panah kiri/kanan, Tab tetap di dalam dialog
  document.addEventListener("keydown", (e) => {
    if (!box.classList.contains("open")) return;
    if (e.key === "Escape") close();
    else if (e.key === "ArrowLeft" && multi) step(-1);
    else if (e.key === "ArrowRight" && multi) step(1);
    else if (e.key === "Tab") {
      const f = [closeBtn, prevBtn, nextBtn].filter((b) => !b.hidden);
      const first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    }
  });
})();


