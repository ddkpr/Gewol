(function sakura() {
  const canvas = document.getElementById("sakura");
  if (!canvas || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  const ctx = canvas.getContext("2d");
  let w, h, petals;

  function resize() {
    w = canvas.width = window.innerWidth;
    h = canvas.height = window.innerHeight;
  }
  window.addEventListener("resize", resize);
  resize();

  const count = window.innerWidth < 600 ? 14 : 26;
  function makePetal(startTop) {
    return {
      x: Math.random() * w,
      y: startTop ? -20 : Math.random() * h,
      size: 6 + Math.random() * 8,
      speed: 0.5 + Math.random() * 1.1,
      drift: 0.3 + Math.random() * 0.8,
      sway: Math.random() * Math.PI * 2,
      rot: Math.random() * Math.PI * 2,
      rotSpeed: (Math.random() - 0.5) * 0.04,
      alpha: 0.35 + Math.random() * 0.4,
    };
  }
  petals = Array.from({ length: count }, () => makePetal(false));

  function drawPetal(p) {
    ctx.save();
    ctx.translate(p.x, p.y);
    ctx.rotate(p.rot);
    ctx.globalAlpha = p.alpha;
    ctx.fillStyle = "#ff8fc7";
    ctx.beginPath();
    ctx.moveTo(0, 0);
    ctx.bezierCurveTo(p.size, -p.size * 0.6, p.size * 1.1, p.size * 0.9, 0, p.size * 1.3);
    ctx.bezierCurveTo(-p.size * 1.1, p.size * 0.9, -p.size, -p.size * 0.6, 0, 0);
    ctx.fill();
    ctx.restore();
  }

  function frame() {
    ctx.clearRect(0, 0, w, h);
    petals.forEach((p, i) => {
      p.sway += 0.02;
      p.x += Math.sin(p.sway) * p.drift;
      p.y += p.speed;
      p.rot += p.rotSpeed;
      drawPetal(p);
      if (p.y > h + 20 || p.x < -30 || p.x > w + 30) petals[i] = makePetal(true);
    });
    requestAnimationFrame(frame);
  }
  frame();
})();

