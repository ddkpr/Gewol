// ===== SINKRONISASI OTOMATIS: TikTok & YouTube @gewolx ===============
// =====================================================================
// CARA PAKAI (pilih salah satu):
//
//  A) PAKAI WORKER (disarankan, TikTok + YouTube, API key aman)
//     1. Deploy file SYNC/worker.js ke Cloudflare Workers (petunjuk ada di file itu).
//     2. Isi WORKER_URL di bawah dengan alamat worker-mu.
//
//  B) TANPA WORKER (hanya YouTube)
//     1. Isi YT_API_KEY di bawah (batasi key ke domain websitemu di Google Cloud).
//     2. TikTok tetap memakai angka manual di index.html (data-count).
//
// Jika dua-duanya kosong atau gagal, angka manual di index.html tetap dipakai.
const SYNC = {
  WORKER_URL: "",                 // contoh: "https://gewol-stats.namakamu.workers.dev"
  YT_API_KEY: "",                 // hanya dipakai jika WORKER_URL kosong
  YT_HANDLE: "gewolx",
  CACHE_MINUTES: 60,              // simpan hasil di browser agar hemat kuota
};

(function syncStats() {
  const CACHE_KEY = "stats_cache_v1";

  function apply(data) {
    const map = { tiktok: data.tiktok, youtube: data.youtube };
    Object.entries(map).forEach(([name, value]) => {
      if (!Number.isFinite(value) || value < 0) return; // abaikan jika tidak valid
      const el = document.querySelector('[data-stat="' + name + '"]');
      if (!el) return;
      el.dataset.count = String(Math.round(value));
      el.dataset.suffix = "";                      // angka asli, tanpa tanda "+"
      if (el.dataset.ran) window.runCounter(el);   // sudah tampil: animasikan ke angka baru
    });
  }

  function readCache() {
    try {
      const c = JSON.parse(localStorage.getItem(CACHE_KEY));
      if (c && c.data) return c;
    } catch (e) {}
    return null;
  }

  async function fetchJson(url) {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), 8000);
    try {
      const res = await fetch(url, { signal: ctrl.signal });
      if (!res.ok) throw new Error("HTTP " + res.status);
      return await res.json();
    } finally {
      clearTimeout(timer);
    }
  }

  async function load() {
    if (SYNC.WORKER_URL) {
      const d = await fetchJson(SYNC.WORKER_URL);
      return { tiktok: d.tiktok ?? null, youtube: d.youtube ?? null };
    }
    if (SYNC.YT_API_KEY) {
      const u = "https://www.googleapis.com/youtube/v3/channels?part=statistics&forHandle=" +
        encodeURIComponent(SYNC.YT_HANDLE) + "&key=" + encodeURIComponent(SYNC.YT_API_KEY);
      const d = await fetchJson(u);
      const st = d.items && d.items[0] && d.items[0].statistics;
      const subs = st && !st.hiddenSubscriberCount ? Number(st.subscriberCount) : null;
      return { tiktok: null, youtube: subs };
    }
    return null; // tidak dikonfigurasi: pakai angka manual
  }

  (async function init() {
    if (!SYNC.WORKER_URL && !SYNC.YT_API_KEY) return;
    const cached = readCache();
    if (cached) {
      apply(cached.data);
      if (Date.now() - cached.time < SYNC.CACHE_MINUTES * 60000) return; // masih segar
    }
    try {
      const data = await load();
      if (!data) return;
      // gabungkan dengan cache lama agar angka yang gagal diambil tidak hilang
      const merged = Object.assign({}, cached && cached.data, Object.fromEntries(
        Object.entries(data).filter(([, v]) => Number.isFinite(v))
      ));
      apply(merged);
      try { localStorage.setItem(CACHE_KEY, JSON.stringify({ time: Date.now(), data: merged })); } catch (e) {}
    } catch (err) {
      console.warn("Sinkronisasi statistik gagal, memakai angka manual:", err);
    }
  })();
})();
